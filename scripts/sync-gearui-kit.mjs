#!/usr/bin/env node
// Pull generated content from a gearui-kit checkout into this site.
//
// The site never hand-maintains anything the kit already knows. Two things
// are synced:
//
//   1. the component index, rendered from the sample's registry
//      (sample/src/commonMain/kotlin/com/gearui/sample/config/ComponentConfig.kt)
//      into docs/gearui-kit/guide/components.md and its zh-Hans twin
//   2. the README screenshots, resized for the web
//
// Usage:
//   node scripts/sync-gearui-kit.mjs [path-to-gearui-kit]   (default ../gearui-kit)
//
// The generated markdown carries a header saying so; edit the registry in the
// kit and rerun, do not edit the output.

import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const site = resolve(here, '..')
const kit = resolve(process.argv[2] ?? resolve(site, '..', 'gearui-kit'))
const registry = resolve(kit, 'sample/src/commonMain/kotlin/com/gearui/sample/config/ComponentConfig.kt')

if (!existsSync(registry)) {
  console.error(`registry not found: ${registry}\npass the gearui-kit checkout as the first argument`)
  process.exit(1)
}

// Registered routes that exercise the runtime rather than ship a component.
// Same list as scripts/gen_component_index.py in the kit; keep them aligned.
const NON_COMPONENT_IDS = new Set(['icon-render', 'runtime-insets', 'navigator-kuikly-spike', 'navigator-v1-demo'])

const ENTRY_RE =
  /ComponentInfo\(\s*"(?<id>[^"]+)",\s*"(?<zh>[^"]*)",\s*"(?<en>[^"]*)",\s*ComponentCategory\.(?<cat>[A-Z_]+),\s*"[^"]*"(?:,\s*"(?<dzh>[^"]*)")?(?:,\s*"(?<den>[^"]*)")?\s*\)/g

const CATEGORY_ORDER = ['BASIC', 'FORM', 'NAVIGATION', 'DATA_DISPLAY', 'FEEDBACK', 'LAYOUT']
const LABEL = {
  en: { BASIC: 'Basic', FORM: 'Form', NAVIGATION: 'Navigation', DATA_DISPLAY: 'Data display', FEEDBACK: 'Feedback', LAYOUT: 'Layout' },
  zh: { BASIC: '基础', FORM: '表单', NAVIGATION: '导航', DATA_DISPLAY: '数据展示', FEEDBACK: '反馈', LAYOUT: '布局' },
}

const src = readFileSync(registry, 'utf8')
const entries = [...src.matchAll(ENTRY_RE)].map((m) => m.groups).filter((e) => !NON_COMPONENT_IDS.has(e.id))
if (entries.length === 0) {
  console.error('no ComponentInfo entries parsed')
  process.exit(1)
}
const byCat = Object.fromEntries(CATEGORY_ORDER.map((c) => [c, []]))
for (const e of entries) (byCat[e.cat] ??= []).push(e)
const total = entries.length
const catCount = CATEGORY_ORDER.filter((c) => byCat[c].length).length

const header = (lang) =>
  lang === 'en'
    ? `<!-- Generated by scripts/sync-gearui-kit.mjs from gearui-kit's ComponentConfig.kt. Do not edit; rerun the script. -->\n`
    : `<!-- 由 scripts/sync-gearui-kit.mjs 从 gearui-kit 的 ComponentConfig.kt 生成。请勿手改；重新运行脚本。 -->\n`

function renderEn() {
  const out = [header('en'), '# Components', '',
    `GearUI Kit ships **${total} components** in ${catCount} categories. Every one of them has a demo page in the sample app; the names below are the composable names you import from \`com.gearui.components.*\`.`, '',
    'This page is generated from the sample\'s component registry, so it cannot disagree with what the sample shows.', '']
  for (const cat of CATEGORY_ORDER) {
    const items = byCat[cat]; if (!items.length) continue
    out.push(`## ${LABEL.en[cat]} (${items.length})`, '', '| Component | Purpose |', '| --- | --- |')
    for (const e of items) out.push(`| \`${e.en}\` | ${e.den ?? ''} |`)
    out.push('')
  }
  out.push('## Not listed here', '',
    'The sample also registers a few routes that are runtime checks rather than components (icon rendering, safe-area snapshot, Navigator spikes). They are useful when working on the kit and are deliberately left out of this count.', '')
  return out.join('\n')
}

function renderZh() {
  const out = [header('zh'), '# 组件', '',
    `GearUI Kit 提供 **${total} 个组件**，分 ${catCount} 类。每一个在 sample 里都有对应演示页；下表中的名字就是你从 \`com.gearui.components.*\` import 的 composable 名。`, '',
    '本页由 sample 的组件注册表生成，因此不会与 sample 实际展示的内容不一致。', '']
  for (const cat of CATEGORY_ORDER) {
    const items = byCat[cat]; if (!items.length) continue
    out.push(`## ${LABEL.zh[cat]}（${items.length}）`, '', '| 组件 | 中文名 | 用途 |', '| --- | --- | --- |')
    for (const e of items) out.push(`| \`${e.en}\` | ${e.zh} | ${e.dzh ?? ''} |`)
    out.push('')
  }
  out.push('## 未列入的条目', '',
    'sample 还注册了几条属于运行时验证而非组件的路由（图标渲染、安全区快照、Navigator 探针）。它们对开发 kit 有用，但刻意不计入上面的数字。', '')
  return out.join('\n')
}

const enPath = resolve(site, 'docs/gearui-kit/guide/components.md')
const zhPath = resolve(site, 'docs/zh-Hans/gearui-kit/guide/components.md')
mkdirSync(dirname(enPath), { recursive: true })
mkdirSync(dirname(zhPath), { recursive: true })
writeFileSync(enPath, renderEn())
writeFileSync(zhPath, renderZh())
console.log(`components: ${total} in ${catCount} categories -> ${enPath}, ${zhPath}`)

// Screenshots. Copied as-is; sizes are kept small in the kit already.
const shotsSrc = resolve(kit, 'docs/screenshots')
const shotsDst = resolve(site, 'docs/public/gearui-kit')
mkdirSync(shotsDst, { recursive: true })
let n = 0
for (const f of ['home-en.png', 'home-zh.png', 'settings-light.png', 'settings-dark.png']) {
  const s = resolve(shotsSrc, f)
  if (existsSync(s)) { copyFileSync(s, resolve(shotsDst, f)); n++ }
}
console.log(`screenshots: ${n} copied -> ${shotsDst}`)
